-- ============================================================================
-- 013_reporting_foundation.sql
-- Reporting schema, the reporting_ro role, conformed dimensions, refresh control
-- and the STUDENT surface (reports S1 and S2).
--
-- Design source: 12-bi-reporting-data-model.md §8-§9.
-- Depends on: 011 (student_exam_targets), 004 (is_student_self / has_role).
--
-- THE RULE THIS FILE EXISTS TO ENFORCE
--   A student may read exactly ONE reporting object, reporting.v_student_today,
--   and that view's column list contains no score, percentage, rank, band or
--   correctness field. mv_student_daily_target does compute `required_daily` and
--   `plan_overload_flag`, but the view does not select them - so even a bug in
--   the RLS predicate cannot show a child their own overload figure.
--
-- Idempotent: safe to re-run.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS reporting;
CREATE EXTENSION IF NOT EXISTS pg_cron;

-- 1. reporting_ro --------------------------------------------------------------
-- NOLOGIN and granted to the existing roles, so the API does SET LOCAL ROLE
-- inside a transaction instead of needing a second connection string through
-- Supavisor. SET ROLE changes current_user but NOT the JWT claims, so auth.uid()
-- keeps working and RLS still applies: a capability reduction, not an identity
-- swap, and not a bypass.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'reporting_ro') THEN
    CREATE ROLE reporting_ro NOLOGIN;
  END IF;
END $$;

GRANT reporting_ro TO authenticated, service_role, postgres;
GRANT USAGE ON SCHEMA reporting TO reporting_ro;

-- ALTER ROLE only applies at login and SET LOCAL ROLE does not re-login, so the
-- API must also issue SET LOCAL statement_timeout. Both are needed.
ALTER ROLE reporting_ro SET statement_timeout = '5s';
ALTER ROLE reporting_ro SET idle_in_transaction_session_timeout = '10s';
ALTER ROLE reporting_ro SET lock_timeout = '2s';

-- 2. dim_date (conformed, Australia/Melbourne) ----------------------------------
CREATE TABLE IF NOT EXISTS reporting.dim_date (
  date_key              integer PRIMARY KEY,
  the_date              date NOT NULL UNIQUE,
  year                  smallint NOT NULL,
  quarter               smallint NOT NULL,
  month                 smallint NOT NULL,
  week_of_year          smallint NOT NULL,
  day_of_week           smallint NOT NULL,
  is_weekend            boolean NOT NULL,
  is_vic_public_holiday boolean NOT NULL DEFAULT false,
  is_school_term        boolean NOT NULL DEFAULT true,   -- ASSUMPTION A-19
  month_start           date NOT NULL,
  month_end             date NOT NULL
);

INSERT INTO reporting.dim_date
  (date_key, the_date, year, quarter, month, week_of_year, day_of_week,
   is_weekend, month_start, month_end)
SELECT to_char(d,'YYYYMMDD')::int, d,
       EXTRACT(YEAR FROM d)::smallint, EXTRACT(QUARTER FROM d)::smallint,
       EXTRACT(MONTH FROM d)::smallint, EXTRACT(WEEK FROM d)::smallint,
       EXTRACT(ISODOW FROM d)::smallint, EXTRACT(ISODOW FROM d) >= 6,
       date_trunc('month', d)::date,
       (date_trunc('month', d) + interval '1 month - 1 day')::date
FROM generate_series(DATE '2024-01-01', DATE '2030-12-31', interval '1 day') AS d
ON CONFLICT (date_key) DO NOTHING;

-- 3. dim_test_family ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reporting.dim_test_family (
  test_family_key smallint PRIMARY KEY,
  exam_type       text NOT NULL UNIQUE,
  family_label    text NOT NULL,
  is_diagnostic   boolean NOT NULL DEFAULT false
);
-- Seeded from the existing public.exam_type enum. Labels are the enum spellings
-- humanised; no exam format, syllabus or external benchmark is implied.
INSERT INTO reporting.dim_test_family (test_family_key, exam_type, family_label, is_diagnostic)
SELECT (row_number() OVER (ORDER BY e.enumlabel))::smallint, e.enumlabel,
       initcap(replace(e.enumlabel, '_', ' ')), e.enumlabel = 'BENCHMARK'
FROM pg_enum e
JOIN pg_type t ON t.oid = e.enumtypid
JOIN pg_namespace n ON n.oid = t.typnamespace
WHERE n.nspname = 'public' AND t.typname = 'exam_type'
ON CONFLICT (exam_type) DO NOTHING;

-- 4. dim_student (SCD Type 2 on year_level) -------------------------------------
CREATE TABLE IF NOT EXISTS reporting.dim_student (
  student_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id  uuid NOT NULL,
  pseudonym   text NOT NULL,
  year_level  smallint NOT NULL CHECK (year_level BETWEEN 2 AND 8),
  valid_from  date NOT NULL,
  valid_to    date NOT NULL DEFAULT '9999-12-31',
  is_current  boolean NOT NULL DEFAULT true,
  UNIQUE (student_id, valid_from)
);
CREATE INDEX IF NOT EXISTS idx_dim_student_id_current
  ON reporting.dim_student (student_id) WHERE is_current;
-- No email, no name, no parent contact detail.

-- 5. dim_year_level_cap (S2's overload protection) ------------------------------
CREATE TABLE IF NOT EXISTS reporting.dim_year_level_cap (
  year_level            smallint PRIMARY KEY CHECK (year_level BETWEEN 2 AND 8),
  -- SEEDED NULL ON PURPOSE. These are child-safety limits and were not supplied;
  -- inventing one would be exactly the fabricated figure the brief prohibits.
  -- Until set (question Q-4) mv_student_daily_target falls back to
  -- weekly_sessions_goal / 7 and plan_overload_flag stays false.
  max_tests_per_day     smallint,
  max_questions_per_day smallint,
  updated_at            timestamptz NOT NULL DEFAULT now()
);
INSERT INTO reporting.dim_year_level_cap (year_level)
SELECT g FROM generate_series(2,8) g ON CONFLICT (year_level) DO NOTHING;

-- 6. dim_practice_plan (SCD Type 2) + parent-set rest days ----------------------
CREATE TABLE IF NOT EXISTS reporting.dim_practice_plan (
