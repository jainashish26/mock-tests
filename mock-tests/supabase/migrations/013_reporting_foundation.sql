  student_id           uuid NOT NULL,
  student_key          bigint,
  target_exam          text,
  exam_date            date,
  total_planned_units  integer NOT NULL DEFAULT 0 CHECK (total_planned_units >= 0),
  unit_kind            text NOT NULL DEFAULT 'tests' CHECK (unit_kind IN ('tests','questions')),
  weekly_sessions_goal smallint NOT NULL DEFAULT 3,
  valid_from           date NOT NULL,
  valid_to             date NOT NULL DEFAULT '9999-12-31',
  is_current           boolean NOT NULL DEFAULT true,
  UNIQUE (student_id, valid_from)
