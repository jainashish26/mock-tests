-- ============================================================================
-- 117 - The reporting function ACL file is generated, not hand-maintained
--
-- THE GAP THIS CLOSES
--   supabase/reset/10_reporting_function_acls.sql exists because
--   pg_get_functiondef does not capture ACLs: a baseline restore creates every
--   reporting function with Postgres's default ACL, which grants EXECUTE to
--   PUBLIC. The file is a static list generated from the live database once, and
--   nothing regenerates it - `schema:rebaseline` does not touch it. So when 111
--   added reporting.load_enquiry_facts, the file kept describing the schema as it
--   was before: on a scratch restore that function is executable by `anon`, and
--   being SECURITY DEFINER and postgres-owned it truncates and rebuilds
--   reporting.fact_enquiry. A read endpoint would have become a write primitive.
--
--   Live is fine - the function is properly locked down here, which is exactly
--   why nothing caught this. The defect only exists on a machine rebuilt from the
--   backup, and a backup whose restore silently widens privileges is not a backup;
--   it is a way of producing a different production.
--
-- WHY GENERATED RATHER THAN APPENDED BY HAND
--   Appending one line fixes today. The next `load_*` added by the next migration
--   reproduces the bug identically and with the same invisibility, because the
--   failure is not in the file, it is in the fact that nobody re-makes it. This is
--   the same shape as the config-table capture discovering its own tables: the
--   capture has to derive from live state, or it drifts quietly forever.
--
-- The emitted text is the file. `reporting_ro` is excluded from the revoke list
-- because it is granted explicitly per function elsewhere, and revoking it here
-- would fight that; PUBLIC/anon/authenticated are the roles the default ACL
-- wrongly reaches.
--
-- Idempotent: safe to re-run.
-- ============================================================================

CREATE OR REPLACE FUNCTION reporting.export_baseline_function_acls()
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'reporting', 'pg_catalog'
AS $f$
DECLARE
  v_out  text := '';
  r      record;
BEGIN
  v_out := '-- GENERATED by reporting.export_baseline_function_acls() - do not hand-edit.' || E'\n'
        || '-- pg_get_functiondef omits ACLs, so a baseline restore leaves every reporting' || E'\n'
        || '-- function PUBLIC-executable. This file replicates the live lock-down and must' || E'\n'
        || '-- be regenerated whenever a reporting function is added or its grants change;' || E'\n'
        || '-- schema:rebaseline does exactly that. Idempotent. Apply AFTER all reporting' || E'\n'
        || '-- function files.' || E'\n\n';

  FOR r IN
    SELECT -- Qualified deliberately. p.oid::regprocedure::text omits the schema
           -- whenever the function is on the current search_path, and this
           -- function's own search_path IS reporting - so the obvious form emits
           -- bare names that would resolve against whatever search_path the
           -- restore harness happens to have set. Same class of bug 033 fixed for
           -- the refresh-lag check and safe_refresh notes for regclass.
           quote_ident(n.nspname) || '.' || quote_ident(p.proname)
             || '(' || pg_get_function_identity_arguments(p.oid) || ')' AS sig,
           p.proname,
           ARRAY['PUBLIC','anon','authenticated'] AS revoke_roles,
           -- Decided from the stored ACL, not has_function_privilege: a function
           -- whose PUBLIC grant was never revoked would report effective access
           -- for service_role and gain a grant it was never given.
           (p.proacl::text LIKE '%service_role=X%') AS to_service
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'reporting'
      AND p.prokind = 'f'
      -- The capture tooling itself is deliberately absent: it is live-only,
      -- excluded from the baseline function count, and cannot exist on a reset
      -- target, so a revoke against it would fail the restore.
      AND p.proname NOT IN ('export_baseline','export_baseline_config',
                            'export_baseline_function_acls')
    ORDER BY p.proname
  LOOP
    v_out := v_out || 'REVOKE ALL ON FUNCTION ' || r.sig
          || ' FROM ' || array_to_string(r.revoke_roles, ', ') || ';' || E'\n';
    IF r.to_service THEN
      v_out := v_out || 'GRANT EXECUTE ON FUNCTION ' || r.sig || ' TO service_role;' || E'\n';
    END IF;
  END LOOP;

  RETURN v_out;
END;
$f$;

REVOKE ALL ON FUNCTION reporting.export_baseline_function_acls() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION reporting.export_baseline_function_acls() TO postgres, service_role;

-- Public entry point, for the same reason export_schema_baseline is public:
-- PostgREST advertises the public schema, so scripts/rebaseline_schema.py can
-- only reach a capture tool that lives there. Without this wrapper the capture
-- step would 404 and the ACL file would quietly stop being regenerated - which is
-- the precise failure this migration exists to prevent, reintroduced by the
-- capture mechanism itself.
CREATE OR REPLACE FUNCTION public.export_baseline_function_acls()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'reporting', 'pg_catalog'
AS $$
  SELECT reporting.export_baseline_function_acls()
$$;

REVOKE ALL ON FUNCTION public.export_baseline_function_acls() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.export_baseline_function_acls() TO postgres, service_role;

-- ----------------------------------------------------------------------------
-- Self-check: the emitted script covers the live schema, including 111's loader
-- ----------------------------------------------------------------------------
DO $$
DECLARE
  v_script text;
  v_count  integer;
  v_live   integer;
BEGIN
  v_script := reporting.export_baseline_function_acls();

  SELECT count(*) INTO v_count
  FROM (SELECT unnest(string_to_array(v_script, E'\n')) AS line) x
  WHERE x.line LIKE 'REVOKE ALL ON FUNCTION%';

  SELECT count(*) INTO v_live
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'reporting' AND p.prokind = 'f'
    AND p.proname NOT IN ('export_baseline','export_baseline_config',
                          'export_baseline_function_acls');

  IF v_count <> v_live THEN
    RAISE EXCEPTION '117 self-test: script covers % functions but live has %',
      v_count, v_live USING ERRCODE = 'raise_exception';
  END IF;

  -- The function that motivated this whole migration must be in the output. If a
  -- future capture drops a name, this fails rather than the restore does.
  IF v_script NOT LIKE '%load_enquiry_facts%' THEN
    RAISE EXCEPTION '117 self-test: the enquiry loader is missing from the ACL script'
      USING ERRCODE = 'raise_exception';
  END IF;

  IF v_script LIKE '%export_baseline_config%' THEN
    RAISE EXCEPTION '117 self-test: capture tooling leaked into the restore script'
      USING ERRCODE = 'raise_exception';
  END IF;
END $$;
