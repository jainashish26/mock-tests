  student_id uuid NOT NULL REFERENCES public.student_profiles(id) ON DELETE CASCADE,
  rest_date  date NOT NULL,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (student_id, rest_date)
);
CREATE INDEX IF NOT EXISTS idx_practice_rest_days_student
  ON public.practice_rest_days (student_id, rest_date);
ALTER TABLE public.practice_rest_days ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Parent can read linked child rest days" ON public.practice_rest_days;
CREATE POLICY "Parent can read linked child rest days"
  ON public.practice_rest_days FOR SELECT USING (public.is_parent_of(student_id));
DROP POLICY IF EXISTS "Parent can manage linked child rest days" ON public.practice_rest_days;
CREATE POLICY "Parent can manage linked child rest days"
  ON public.practice_rest_days FOR ALL
  USING (public.is_parent_of(student_id)) WITH CHECK (public.is_parent_of(student_id));
DROP POLICY IF EXISTS "Admin can manage all rest days" ON public.practice_rest_days;
CREATE POLICY "Admin can manage all rest days"
  ON public.practice_rest_days FOR ALL
  USING (public.has_role('ADMIN')) WITH CHECK (public.has_role('ADMIN'));
-- No STUDENT policy: a parent sets rest days, a child does not.

-- 7. Refresh control -------------------------------------------------------------
-- Blackouts are DATA, not code: an ops change needs no deploy and the whole
-- schedule is reviewable in one query.
CREATE TABLE IF NOT EXISTS reporting.refresh_blackout (
  blackout_id  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reason       text NOT NULL,
  from_time    time NOT NULL,
  to_time      time NOT NULL,
  days_of_week smallint[] NOT NULL DEFAULT '{1,2,3,4,5,6,7}',
  is_active    boolean NOT NULL DEFAULT true,
  valid_from   date,
  valid_to     date
);
-- SEEDED AS ASSUMPTION A-07, NOT A MEASURED FACT. Nothing in the repo or database
-- records real peak test windows. Replace with measured peaks from report A14.
INSERT INTO reporting.refresh_blackout (reason, from_time, to_time, days_of_week)
SELECT v.reason, v.from_time, v.to_time, v.days_of_week
FROM (VALUES
  ('Assumed weekday evening practice peak', '16:00'::time, '21:00'::time, '{1,2,3,4,5}'::smallint[]),
  ('Assumed weekend morning practice peak', '09:00'::time, '13:00'::time, '{6,7}'::smallint[])
) AS v(reason, from_time, to_time, days_of_week)
WHERE NOT EXISTS (SELECT 1 FROM reporting.refresh_blackout);

CREATE TABLE IF NOT EXISTS reporting.refresh_log (
  refresh_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  object_name  text NOT NULL,
  started_at   timestamptz NOT NULL DEFAULT now(),
  finished_at  timestamptz,
  duration_ms  integer,
  row_count    bigint,
  -- `concurrently` is a RESERVED word in Postgres (REFRESH/CREATE INDEX
  -- CONCURRENTLY) and cannot be an unquoted column name.
  ran_concurrently boolean NOT NULL DEFAULT true,
  status       text NOT NULL DEFAULT 'running',
  error_text   text
);
CREATE INDEX IF NOT EXISTS idx_refresh_log_object
  ON reporting.refresh_log (object_name, started_at DESC);

CREATE TABLE IF NOT EXISTS reporting.etl_watermark (
  object_name text PRIMARY KEY,
  high_water  timestamptz NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION reporting.in_blackout()
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM reporting.refresh_blackout b
    CROSS JOIN LATERAL (SELECT (now() AT TIME ZONE 'Australia/Melbourne') AS mel) t
    WHERE b.is_active
      AND (b.valid_from IS NULL OR t.mel::date >= b.valid_from)
      AND (b.valid_to   IS NULL OR t.mel::date <= b.valid_to)
      AND EXTRACT(ISODOW FROM t.mel)::smallint = ANY (b.days_of_week)
      -- Covers windows that do and do not cross midnight.
      AND ((b.from_time <= b.to_time AND t.mel::time BETWEEN b.from_time AND b.to_time)
        OR (b.from_time >  b.to_time AND (t.mel::time >= b.from_time OR t.mel::time <= b.to_time)))
  );
$$;

-- One wrapper for every scheduled refresh: guarded, logged, timeout-bound.
CREATE OR REPLACE FUNCTION reporting.safe_refresh(p_object regclass, p_concurrently boolean DEFAULT true)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = reporting, public AS $$
DECLARE v_id bigint; v_started timestamptz := clock_timestamp();
BEGIN
  -- Maintenance, not a dashboard query: longer than reporting_ro's 5s, still a
  -- hard stop.
  SET LOCAL statement_timeout = '10min';
  SET LOCAL lock_timeout = '30s';

  IF reporting.in_blackout() THEN
    INSERT INTO reporting.refresh_log (object_name, ran_concurrently, status, finished_at)
    VALUES (p_object::text, p_concurrently, 'skipped_blackout', clock_timestamp());
    RETURN;
  END IF;

  INSERT INTO reporting.refresh_log (object_name, ran_concurrently)
  VALUES (p_object::text, p_concurrently) RETURNING refresh_id INTO v_id;

  BEGIN
    IF p_concurrently THEN
      EXECUTE format('REFRESH MATERIALIZED VIEW CONCURRENTLY %s', p_object::text);
    ELSE
      EXECUTE format('REFRESH MATERIALIZED VIEW %s', p_object::text);
    END IF;
    UPDATE reporting.refresh_log
       SET finished_at = clock_timestamp(),
           duration_ms = EXTRACT(EPOCH FROM clock_timestamp() - v_started) * 1000,
           status = 'ok'
     WHERE refresh_id = v_id;
  EXCEPTION WHEN OTHERS THEN
    UPDATE reporting.refresh_log
       SET finished_at = clock_timestamp(), status = 'failed', error_text = SQLERRM
     WHERE refresh_id = v_id;
    RAISE;   -- re-raise so pg_cron records it and alert AL-28 fires
  END;
END; $$;
REVOKE ALL ON FUNCTION reporting.safe_refresh(regclass, boolean) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION reporting.safe_refresh(regclass, boolean) TO service_role, postgres;

-- ----------------------------------------------------------------------------
-- 8. ETL: public -> reporting dimensions ---------------------------------------
-- ----------------------------------------------------------------------------
-- SECURITY DEFINER because it reads public tables that reporting_ro cannot.
CREATE OR REPLACE FUNCTION reporting.load_student_dims()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = reporting, public AS $$
DECLARE v_today date := (now() AT TIME ZONE 'Australia/Melbourne')::date;
BEGIN
  -- dim_student, SCD Type 2 on year_level: close the old row and open a new one
  -- only when the year level actually changed. A Year 3 attempt must stay a
  -- Year 3 attempt forever (test DA-10).
  UPDATE reporting.dim_student ds
     SET valid_to = v_today - 1, is_current = false
  FROM public.student_profiles sp
  WHERE sp.id = ds.student_id AND ds.is_current AND ds.year_level <> sp.year_level;

  INSERT INTO reporting.dim_student (student_id, pseudonym, year_level, valid_from)
  SELECT sp.id, sp.username, sp.year_level::smallint, v_today
  FROM public.student_profiles sp
  WHERE NOT EXISTS (
    SELECT 1 FROM reporting.dim_student d
    WHERE d.student_id = sp.id AND d.is_current AND d.year_level = sp.year_level);

  -- dim_practice_plan, SCD Type 2 on the plan's substantive attributes.
  UPDATE reporting.dim_practice_plan dp
     SET valid_to = v_today - 1, is_current = false
  FROM public.student_exam_targets t
  WHERE t.student_id = dp.student_id AND dp.is_current
    AND (dp.exam_date IS DISTINCT FROM t.exam_date
      OR dp.target_exam IS DISTINCT FROM t.target_exam
      OR dp.weekly_sessions_goal <> t.weekly_sessions_goal);

  INSERT INTO reporting.dim_practice_plan
    (student_id, target_exam, exam_date, total_planned_units, unit_kind,
     weekly_sessions_goal, valid_from)
  SELECT t.student_id, t.target_exam, t.exam_date, 0, 'tests',
         t.weekly_sessions_goal::smallint, v_today
  FROM public.student_exam_targets t
  WHERE NOT EXISTS (
    SELECT 1 FROM reporting.dim_practice_plan p
    WHERE p.student_id = t.student_id AND p.is_current
      AND p.exam_date IS NOT DISTINCT FROM t.exam_date
      AND p.target_exam IS NOT DISTINCT FROM t.target_exam
      AND p.weekly_sessions_goal = t.weekly_sessions_goal);

  -- Link plan rows to the student surrogate key.
  UPDATE reporting.dim_practice_plan dp
     SET student_key = ds.student_key
  FROM reporting.dim_student ds
  WHERE ds.student_id = dp.student_id AND ds.is_current AND dp.student_key IS NULL;

  -- total_planned_units is not set by any UI yet; default to one planned test per
  -- week between today and the exam date rather than leaving it 0 (which would
  -- make every daily target 0 and the feature look broken).
  UPDATE reporting.dim_practice_plan dp
     SET total_planned_units = GREATEST(0, CEIL(
           (dp.exam_date - v_today)::numeric / 7 * dp.weekly_sessions_goal)::int)
   WHERE dp.is_current AND dp.exam_date IS NOT NULL AND dp.total_planned_units = 0;
END; $$;
REVOKE ALL ON FUNCTION reporting.load_student_dims() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION reporting.load_student_dims() TO service_role, postgres;

-- ----------------------------------------------------------------------------
-- 9. Student materialised views (S1, S2) ---------------------------------------
-- ----------------------------------------------------------------------------
-- S1: countdown. Contains NO score column of any kind.
CREATE MATERIALIZED VIEW IF NOT EXISTS reporting.mv_student_countdown AS
SELECT ds.student_key, ds.student_id, ds.pseudonym,
       dp.target_exam AS exam_label, dp.exam_date,
       GREATEST(0, dp.exam_date - (now() AT TIME ZONE 'Australia/Melbourne')::date) AS days_to_exam,
       (dp.exam_date < (now() AT TIME ZONE 'Australia/Melbourne')::date)            AS exam_passed
FROM reporting.dim_practice_plan dp
JOIN reporting.dim_student ds ON ds.student_key = dp.student_key AND ds.is_current
WHERE dp.is_current AND dp.exam_date IS NOT NULL;

-- REQUIRED for REFRESH ... CONCURRENTLY (test DA-17).
CREATE UNIQUE INDEX IF NOT EXISTS ux_mv_student_countdown
  ON reporting.mv_student_countdown (student_key);

-- S2: daily target. The cap always wins.
CREATE MATERIALIZED VIEW IF NOT EXISTS reporting.mv_student_daily_target AS
WITH done AS (
  SELECT ds.student_key, COUNT(*) AS units_completed
  FROM public.funnel_events fe
  JOIN reporting.dim_student ds ON ds.student_id = fe.student_id AND ds.is_current
  WHERE fe.event IN ('TEST_SUBMITTED','DIAGNOSTIC_COMPLETED','SECOND_SESSION_COMPLETED')
  GROUP BY ds.student_key
),
rest AS (
  SELECT ds.student_key, COUNT(*) AS rest_days_remaining
  FROM public.practice_rest_days r
  JOIN reporting.dim_student ds ON ds.student_id = r.student_id AND ds.is_current
  WHERE r.rest_date > (now() AT TIME ZONE 'Australia/Melbourne')::date
  GROUP BY ds.student_key
),
calc AS (
  SELECT dp.plan_key, dp.student_key, dp.unit_kind, dp.weekly_sessions_goal,
         GREATEST(0, dp.total_planned_units - COALESCE(d.units_completed,0)) AS remaining_units,
         GREATEST(0, (dp.exam_date - (now() AT TIME ZONE 'Australia/Melbourne')::date)
                     - COALESCE(r.rest_days_remaining,0))                   AS remaining_days
  FROM reporting.dim_practice_plan dp
  LEFT JOIN done d ON d.student_key = dp.student_key
  LEFT JOIN rest r ON r.student_key = dp.student_key
  WHERE dp.is_current AND dp.exam_date IS NOT NULL
)
SELECT c.plan_key, c.student_key, c.unit_kind, c.remaining_units, c.remaining_days,
  CASE WHEN c.remaining_days <= 0 THEN 0
       ELSE CEIL(c.remaining_units::numeric / c.remaining_days) END AS required_daily,
  -- THE CAP ALWAYS WINS. NULL cap => fall back to the weekly goal (assumption A-11).
  LEAST(
    CASE WHEN c.remaining_days <= 0 THEN 0
         ELSE CEIL(c.remaining_units::numeric / c.remaining_days) END,
    COALESCE(CASE WHEN c.unit_kind = 'tests'     THEN cap.max_tests_per_day
                  WHEN c.unit_kind = 'questions' THEN cap.max_questions_per_day END,
             CEIL(c.weekly_sessions_goal::numeric / 7))
  )::int AS daily_target_units,
  (c.remaining_days > 0
   AND CEIL(c.remaining_units::numeric / c.remaining_days) >
       COALESCE(CASE WHEN c.unit_kind='tests' THEN cap.max_tests_per_day
                     ELSE cap.max_questions_per_day END, 2147483647)
  ) AS plan_overload_flag
FROM calc c
JOIN reporting.dim_student ds ON ds.student_key = c.student_key AND ds.is_current
LEFT JOIN reporting.dim_year_level_cap cap ON cap.year_level = ds.year_level;

CREATE UNIQUE INDEX IF NOT EXISTS ux_mv_student_daily_target
  ON reporting.mv_student_daily_target (student_key);

-- ----------------------------------------------------------------------------
-- 10. v_student_today - THE ONLY reporting object a student may read ------------
-- ----------------------------------------------------------------------------
-- `required_daily` and `plan_overload_flag` are deliberately NOT selected, so even
-- a bug in the RLS predicate below cannot show a child their overload figure.
CREATE OR REPLACE VIEW reporting.v_student_today AS
SELECT ds.student_id,
       c.exam_label, c.exam_date, c.days_to_exam, c.exam_passed,
       t.daily_target_units, t.unit_kind
FROM reporting.dim_student ds
LEFT JOIN reporting.mv_student_countdown    c ON c.student_key = ds.student_key
LEFT JOIN reporting.mv_student_daily_target t ON t.student_key = ds.student_key
WHERE ds.is_current AND public.is_student_self(ds.student_id);

-- ----------------------------------------------------------------------------
-- 11. RLS + grants --------------------------------------------------------------
-- ----------------------------------------------------------------------------
-- Deny by default, then FORCE so the owner cannot bypass its own policies.
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'reporting' AND c.relkind IN ('r','v','m')
  LOOP
    EXECUTE format('ALTER TABLE reporting.%I ENABLE ROW LEVEL SECURITY', r.relname);
    EXECUTE format('ALTER TABLE reporting.%I FORCE ROW LEVEL SECURITY', r.relname);
  END LOOP;
END $$;

DROP POLICY IF EXISTS student_reads_own_today ON reporting.v_student_today;
CREATE POLICY student_reads_own_today ON reporting.v_student_today
  FOR SELECT TO authenticated
  USING (public.has_role('STUDENT') AND public.is_student_self(student_id));

-- A parent reads the same view for a linked child (drives P9's plan display).
DROP POLICY IF EXISTS parent_reads_child_today ON reporting.v_student_today;
CREATE POLICY parent_reads_child_today ON reporting.v_student_today
  FOR SELECT TO authenticated
  USING (public.has_role('PARENT') AND public.is_parent_of(student_id));

DROP POLICY IF EXISTS admin_reads_student_today ON reporting.v_student_today;
CREATE POLICY admin_reads_student_today ON reporting.v_student_today
  FOR SELECT TO authenticated USING (public.has_role('ADMIN'));

-- SELECT for reporting_ro on views and MVs only. There is deliberately no grant
-- on any public results table, so a reporting query physically cannot read one.
GRANT SELECT ON ALL TABLES IN SCHEMA reporting TO reporting_ro;
ALTER DEFAULT PRIVILEGES IN SCHEMA reporting GRANT SELECT ON TABLES TO reporting_ro;
REVOKE ALL ON SCHEMA reporting FROM PUBLIC, anon;

-- ----------------------------------------------------------------------------
-- 12. pg_cron schedules ---------------------------------------------------------
-- ----------------------------------------------------------------------------
-- cron.schedule takes UTC; Melbourne is UTC+10 (AEST) or +11 (AEDT), so the local
-- time drifts with daylight saving. The blackout guard makes that safe: a schedule
-- that drifts into a peak window is skipped and logged, not run.
SELECT cron.schedule('rpt-load-student-dims', '45 17 * * *',
  $$SELECT reporting.load_student_dims()$$);
SELECT cron.schedule('rpt-student-daily', '0 18 * * *',
  $$SELECT reporting.safe_refresh('reporting.mv_student_countdown', true),
           reporting.safe_refresh('reporting.mv_student_daily_target', true)$$);

COMMENT ON VIEW reporting.v_student_today IS
  'The ONLY reporting object readable by the STUDENT role. Its column list contains no score, percentage, percentile, rank, band, correctness or mastery field, and it omits required_daily and plan_overload_flag so the overload figure can never reach a child.';
