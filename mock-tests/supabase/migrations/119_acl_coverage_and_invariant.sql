-- ============================================================================
-- 119 - The ACL capture covers every reporting function, and the invariant
--         measures the property it is actually supposed to guarantee
--
-- WHAT 117 GOT WRONG, AND HOW IT WAS FOUND
--   117's generator excluded three names on the stated grounds that the capture
--   tooling is "live-only by design" and "therefore absent from any reset
--   target". Checked against the capture it emits: `export_baseline_config` and
--   `export_baseline_function_acls` are BOTH present in baseline/02_functions.sql.
--   They are restored. They were absent from the ACL script. On a rebuilt database
--   they would carry Postgres's default function ACL, which grants EXECUTE to
--   PUBLIC, while live grants it to nobody.
--
--   The exclusion was a belief about the capture rather than a fact taken from it,
--   and it sat in the one file whose whole job is to keep the capture honest. This
--   migration replaces the belief with the rule: revoke for every reporting
--   function that exists, and let the harness tolerate a name a particular target
--   does not have. Over-covering costs an ignorable error on a missing function;
--   under-covering is a silent privilege widening on a restore, which is precisely
--   the defect class 117 was supposed to end.
--
-- THE INVARIANT THAT WAS MISSING
--   "No reporting function is reachable by anon" is the question an operator asks,
--   but it can be answered `true` for the wrong reason: reporting has no USAGE
--   grant for anon, so a PUBLIC-executable function is unreachable whether or not
--   it was revoked. That is a real protection, and it is why the check passed - it
--   just does not detect an ACL file that failed to apply. Added below: no
--   reporting function may carry the default ACL at all. That one is sensitive to
--   exactly the failure being guarded against, and on live it is already true.
--
-- Idempotent: safe to re-run.
-- ============================================================================

CREATE OR REPLACE FUNCTION reporting.export_baseline_function_acls()
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'reporting', 'pg_catalog'
AS $f$
DECLARE
  v_out text := '';
  r     record;
BEGIN
  v_out := '-- GENERATED by reporting.export_baseline_function_acls() - do not hand-edit.' || E'\n'
        || '-- pg_get_functiondef omits ACLs, so a baseline restore recreates every reporting' || E'\n'
        || '-- function with the default ACL, which grants EXECUTE to PUBLIC. This file is the' || E'\n'
        || '-- lock-down. Regenerated by schema:rebaseline alongside the capture it protects,' || E'\n'
        || '-- because a hand-maintained copy drifts (117/118). Apply AFTER all reporting' || E'\n'
        || '-- function files; the reset harness applies it tolerantly so a target lacking one' || E'\n'
        || '-- of these names skips that statement rather than aborting the restore.' || E'\n'
        || '--' || E'\n'
        || '-- Coverage is every reporting function, with no exclusions. 117 excluded capture' || E'\n'
        || '-- tooling on the belief that it was absent from a reset target; it is present, so' || E'\n'
        || '-- excluding it left those functions PUBLIC-executable after a restore. Over-covering' || E'\n'
        || '-- is harmless under tolerant application; under-covering is not.' || E'\n\n';

  FOR r IN
    SELECT -- Qualified, for the reason 117 records: p.oid::regprocedure::text
           -- drops the schema when the function is on the current search_path,
           -- and this function's own search_path IS reporting.
           quote_ident(n.nspname) || '.' || quote_ident(p.proname)
             || '(' || pg_get_function_identity_arguments(p.oid) || ')' AS sig,
           -- Decided from the stored ACL rather than effective privilege: a
           -- function reachable through a schema grant would otherwise be given
           -- a service_role EXECUTE grant it has never actually been issued.
           (p.proacl::text LIKE '%service_role=X%') AS to_service
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'reporting'
      AND p.prokind = 'f'
    ORDER BY p.proname
  LOOP
    v_out := v_out || 'REVOKE ALL ON FUNCTION ' || r.sig
          || ' FROM PUBLIC, anon, authenticated;' || E'\n';
    IF r.to_service THEN
      v_out := v_out || 'GRANT EXECUTE ON FUNCTION ' || r.sig || ' TO service_role;' || E'\n';
    END IF;
  END LOOP;

  RETURN v_out;
END;
$f$;

REVOKE ALL ON FUNCTION reporting.export_baseline_function_acls() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION reporting.export_baseline_function_acls() TO postgres, service_role;

CREATE OR REPLACE FUNCTION public.export_baseline_function_acls()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'reporting', 'pg_catalog'
AS $$
  SELECT reporting.export_baseline_function_acls();
$$;

REVOKE ALL ON FUNCTION public.export_baseline_function_acls() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.export_baseline_function_acls() TO postgres, service_role;

-- ----------------------------------------------------------------------------
-- The invariants, with the one that actually detects a failed ACL file
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION reporting.privilege_parity_checks()
RETURNS TABLE(name text, holds boolean)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'reporting', 'public', 'pg_catalog'
AS $v$
BEGIN
  RETURN QUERY SELECT 'no reporting function is reachable by anon', NOT EXISTS (
    SELECT 1 FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'reporting' AND p.prokind = 'f'
      AND has_function_privilege('anon', p.oid::regprocedure, 'EXECUTE')
  );

  -- The sensitive one. reporting has no USAGE grant for anon, so the check above
  -- can read true purely because the schema is unreachable - correct protection,
  -- but blind to an ACL file that never applied. A default ACL (proacl IS NULL)
  -- means "EXECUTE to PUBLIC", which is exactly the state a restore is left in
  -- when this lock-down is missing or incomplete, so this is the question whose
  -- answer actually depends on the thing being verified.
  RETURN QUERY SELECT 'no reporting function carries the default PUBLIC ACL', NOT EXISTS (
    SELECT 1 FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'reporting' AND p.prokind = 'f' AND p.proacl IS NULL
  );

  RETURN QUERY SELECT 'no reporting loader is executable by reporting_ro', NOT EXISTS (
    SELECT 1 FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'reporting' AND p.prokind = 'f'
      AND p.proname LIKE 'load\_%'
      AND has_function_privilege('reporting_ro', p.oid::regprocedure, 'EXECUTE')
  );

  RETURN QUERY SELECT 'service_role cannot edit the contact audit log',
    NOT has_table_privilege('service_role', 'public.enquiry_contact_access_log', 'UPDATE')
    AND NOT has_table_privilege('service_role', 'public.enquiry_contact_access_log', 'DELETE');

  RETURN QUERY SELECT 'inbound capture is not reachable by app roles',
    NOT has_function_privilege('anon',
      'public.record_inbound_email(text,text,text,text,timestamptz,jsonb)', 'EXECUTE')
    AND NOT has_function_privilege('authenticated',
      'public.record_inbound_email(text,text,text,text,timestamptz,jsonb)', 'EXECUTE');

  RETURN QUERY SELECT 'enquiry_contacts is unreadable by app roles',
    NOT has_table_privilege('authenticated', 'public.enquiry_contacts', 'SELECT')
    AND NOT has_table_privilege('anon', 'public.enquiry_contacts', 'SELECT');

  RETURN QUERY SELECT 'every reporting table forces RLS', NOT EXISTS (
    SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'reporting' AND c.relkind = 'r'
      AND (NOT c.relrowsecurity OR NOT c.relforcerowsecurity)
  );
END;
$v$;

REVOKE ALL ON FUNCTION reporting.privilege_parity_checks() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION reporting.privilege_parity_checks() TO postgres, service_role;

CREATE OR REPLACE FUNCTION public.privilege_parity_checks()
RETURNS TABLE(name text, holds boolean)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'reporting', 'pg_catalog'
AS $$
  SELECT * FROM reporting.privilege_parity_checks();
$$;

REVOKE ALL ON FUNCTION public.privilege_parity_checks() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.privilege_parity_checks() TO postgres, service_role;

-- ----------------------------------------------------------------------------
-- Self-check: the generator must cover what the catalog contains
-- ----------------------------------------------------------------------------
DO $$
DECLARE
  v_script   text;
  v_named    integer;
  v_live     integer;
  v_bad      text;
BEGIN
  SELECT count(*) INTO v_live
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'reporting' AND p.prokind = 'f';

  v_script := reporting.export_baseline_function_acls();

  SELECT count(*) INTO v_named
  FROM (SELECT unnest(string_to_array(v_script, E'\n')) AS line) x
  WHERE x.line LIKE 'REVOKE ALL ON FUNCTION%';

  -- No exclusions means these must now be equal, not merely comparable.
  IF v_named <> v_live THEN
    RAISE EXCEPTION
      '119 self-test: ACL script names % reporting functions but live has % - coverage must be exact',
      v_named, v_live USING ERRCODE = 'raise_exception';
  END IF;

  -- The two functions 117 wrongly left out must be present now.
  IF v_script NOT LIKE '%export_baseline_config%' OR v_script NOT LIKE '%export_baseline_function_acls(%' THEN
    RAISE EXCEPTION
      '119 self-test: capture tooling is still missing from the ACL script'
      USING ERRCODE = 'raise_exception';
  END IF;

  SELECT string_agg(x.name, ', ') INTO v_bad
  FROM (SELECT c.name FROM public.privilege_parity_checks() c WHERE NOT c.holds) x;

  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION
      '119 self-test: live violates % - a parity reference that live itself misses can only ever blame the restore',
      v_bad USING ERRCODE = 'raise_exception';
  END IF;

  IF (SELECT count(*) FROM public.privilege_parity_checks()) < 7 THEN
    RAISE EXCEPTION '119 self-test: expected 7 privilege invariants'
      USING ERRCODE = 'raise_exception';
  END IF;
END $$;
